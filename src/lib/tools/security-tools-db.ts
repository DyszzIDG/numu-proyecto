/**
 * Get tools by category
 */
export function getToolsByCategory(category: string): SecurityTool[] {
    return SECURITY_TOOLS.filter(tool => tool.category === category);
}

/**
 * Get tool by ID
 */
export function getToolById(id: string): SecurityTool | undefined {
    return SECURITY_TOOLS.find(tool => tool.id === id);
}

/**
 * Get all categories with tool counts
 */
export function getCategoriesWithCounts(): Array<{ category: string; count: number }> {
    const categories = Object.values(TOOL_CATEGORIES);
    return categories.map(category => ({
        category,
        count: getToolsByCategory(category).length,
    }));
}

/**
 * Search tools by name or tags
 */
export function searchTools(query: string): SecurityTool[] {
    const lowerQuery = query.toLowerCase();
    return SECURITY_TOOLS.filter(
        tool =>
            tool.name.toLowerCase().includes(lowerQuery) ||
            tool.description.toLowerCase().includes(lowerQuery) ||
            tool.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
    );
}

/**
 * Get Red Team tools (offensive)
 */
export function getRedTeamTools(): SecurityTool[] {
    return SECURITY_TOOLS.filter(tool => tool.team === 'red' || tool.team === 'both');
}

/**
 * Get Blue Team tools (defensive)
 */
export function getBlueTeamTools(): SecurityTool[] {
    return SECURITY_TOOLS.filter(tool => tool.team === 'blue' || tool.team === 'both');
}

