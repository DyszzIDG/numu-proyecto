import jsPDF from 'jspdf';

interface ScanResult {
    id: string;
    tool: string;
    target: string;
    scanType: string;
    confidence: number;
    command: string;
    explanation: string;
    flags: string[];
    timestamp: Date;
    status: string;
    findings?: any[];
    rawOutput?: string;
}

export class ReportGenerator {

    /**
     * Generate PDF report from scan result
     */
    static generatePDF(scanResult: ScanResult): void {
        const doc = new jsPDF();

        // Header
        doc.setFontSize(20);
        doc.setTextColor(0, 150, 200);
        doc.text('NUMU Security Scan Report', 20, 20);

        // Metadata
        doc.setFontSize(10);
        doc.setTextColor(100, 100, 100);
        doc.text(`Generated: ${new Date().toLocaleString()}`, 20, 30);
        doc.text(`Scan ID: ${scanResult.id}`, 20, 35);

        // Divider
        doc.setDrawColor(200, 200, 200);
        doc.line(20, 40, 190, 40);

        // Scan Details
        doc.setFontSize(14);
        doc.setTextColor(0, 0, 0);
        doc.text('Scan Details', 20, 50);

        doc.setFontSize(10);
        doc.text(`Tool: ${scanResult.tool.toUpperCase()}`, 30, 60);
        doc.text(`Target: ${scanResult.target}`, 30, 67);
        doc.text(`Scan Type: ${scanResult.scanType}`, 30, 74);
        doc.text(`Confidence: ${Math.round(scanResult.confidence)}%`, 30, 81);
        doc.text(`Status: ${scanResult.status}`, 30, 88);

        // Command
        doc.setFontSize(14);
        doc.text('Command Executed', 20, 100);

        doc.setFontSize(9);
        doc.setFont('courier');
        doc.setTextColor(0, 150, 0);
        const commandLines = doc.splitTextToSize(scanResult.command, 170);
        doc.text(commandLines, 30, 110);

        // AI Analysis
        doc.setFont('helvetica');
        doc.setTextColor(0, 0, 0);
        doc.setFontSize(14);
        const yPos = 110 + (commandLines.length * 5) + 10;
        doc.text('AI Analysis', 20, yPos);

        doc.setFontSize(10);
        const explanationLines = doc.splitTextToSize(scanResult.explanation, 170);
        doc.text(explanationLines, 30, yPos + 10);

        // Findings (if available)
        if (scanResult.findings && scanResult.findings.length > 0) {
            const findingsYPos = yPos + 10 + (explanationLines.length * 5) + 10;

            if (findingsYPos < 270) { // Check if we have space
                doc.setFontSize(14);
                doc.text('Findings', 20, findingsYPos);

                doc.setFontSize(10);
                scanResult.findings.slice(0, 5).forEach((finding, idx) => {
                    const findingY = findingsYPos + 10 + (idx * 15);
                    if (findingY < 280) {
                        doc.setTextColor(200, 0, 0);
                        doc.text(`• ${finding.severity?.toUpperCase() || 'INFO'}`, 30, findingY);
                        doc.setTextColor(0, 0, 0);
                        doc.text(finding.title || 'Finding', 60, findingY);
                    }
                });
            }
        }

        // Footer
        doc.setFontSize(8);
        doc.setTextColor(150, 150, 150);
        doc.text('NUMU Cyber Security Platform - Confidential', 105, 285, { align: 'center' });

        // Save
        doc.save(`numu-scan-${scanResult.tool}-${scanResult.target}-${Date.now()}.pdf`);
    }

    /**
     * Generate Markdown report from scan result
     */
    static generateMarkdown(scanResult: ScanResult): string {
        const md = `# NUMU Security Scan Report

**Generated:** ${new Date().toLocaleString()}  
**Scan ID:** \`${scanResult.id}\`

---

## 📊 Scan Details

| Property | Value |
|----------|-------|
| **Tool** | \`${scanResult.tool.toUpperCase()}\` |
| **Target** | \`${scanResult.target}\` |
| **Scan Type** | ${scanResult.scanType} |
| **Confidence** | ${Math.round(scanResult.confidence)}% |
| **Status** | ${scanResult.status} |
| **Timestamp** | ${scanResult.timestamp.toLocaleString()} |

---

## 💻 Command Executed

\`\`\`bash
${scanResult.command}
\`\`\`

---

## 🤖 AI Analysis

${scanResult.explanation}

---

## 🔍 Findings

${scanResult.findings && scanResult.findings.length > 0
                ? scanResult.findings.map(f => `### ${f.severity?.toUpperCase() || 'INFO'}: ${f.title}

${f.description || 'No description available'}

`).join('\n')
                : '*No findings recorded*'}

---

## 📝 Raw Output

${scanResult.rawOutput
                ? `\`\`\`
${scanResult.rawOutput.substring(0, 1000)}${scanResult.rawOutput.length > 1000 ? '\n...(truncated)' : ''}
\`\`\``
                : '*No raw output available*'}

---

*Generated by NUMU Cyber Security Platform*
`;

        return md;
    }

    /**
     * Download markdown as file
     */
    static downloadMarkdown(scanResult: ScanResult): void {
        const markdown = this.generateMarkdown(scanResult);
        const blob = new Blob([markdown], { type: 'text/markdown' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `numu-scan-${scanResult.tool}-${scanResult.target}-${Date.now()}.md`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }

    /**
     * Copy markdown to clipboard
     */
    static async copyMarkdownToClipboard(scanResult: ScanResult): Promise<void> {
        const markdown = this.generateMarkdown(scanResult);
        await navigator.clipboard.writeText(markdown);
    }
}
